def main() -> int:
    rows = list(ROWS)

    # 若集合产物存在，把实际中位数值回填到 R5 行，避免文档与产物脱钩
    if ENSEMBLE.exists():
        try:
            data = json.loads(ENSEMBLE.read_text(encoding="utf-8"))
            ha = data.get("ha", {})
            co = data.get("co", {})
            for row in rows:
                if row["编号"] == "R5" and ha.get("joint_gate_mw_median") is not None:
                    row["主张"] = (
                        f"10 年多序列联合边界中位数：HA {ha['joint_gate_mw_median']:.0f} MW、"
                        f"CO {co['joint_gate_mw_median']:.0f} MW"
                        f"（{ha.get('sequences')} 条序列）"
                    )
        except (json.JSONDecodeError, KeyError, TypeError):
            pass

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)

    print(f"written -> {OUT}  ({len(rows)} 条主张)")
    print("\nestimand 枚举：")
    for key, label in ESTIMANDS.items():
        print(f"  {key}: {label}")

    missing = [r["编号"] for r in rows if r["estimand"] == "?"]
    if missing:
        print(f"\n⚠️ 未绑定 estimand：{missing}")
    else:
        print("\n✅ 所有主张均已绑定 estimand 与适用范围")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

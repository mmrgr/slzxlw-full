def main() -> None:
    text = MS.read_text(encoding="utf-8")
    # 参考文献剔除，避免 DOI 中的数字造成假阳
    body = re.sub(r"^## References\s*$.*", "", text, flags=re.M | re.S)

    fails = []
    for label, needles in REQUIRED:
        if not any(n in body for n in needles):
            fails.append((label, needles))

    print(f"反向数字门禁　通过 {len(REQUIRED)-len(fails)}/{len(REQUIRED)}")
    for label, needles in fails:
        print(f"  ❌ 缺失：{label}　期望其一：{needles}")
    if not fails:
        print("\n✅ 六个核心强度依赖的全部数字均已在英文稿中出现")
    # 2026-10-19 审计修复：补正确退出码。此前无 sys.exit，失败只靠 ❌ 传递，
    # 而父门禁曾以 gbk 解码导致 ❌ 检测失效 → 该门禁无论成败都判通过。
    sys.exit(0 if not fails else 1)


if __name__ == "__main__":
    main()

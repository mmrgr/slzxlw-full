"""图注生成工具: 让 fig*_caption.md 由脚本生成, 而非手工维护 (2026-10-17).

【背景】
2026-10-17 发现 6 个图注中有 2 个含错误数字:
  · fig3 写 "239 rows excluded" —— 实际 1052-839=213
  · fig5 写 "512 points"       —— 实际 128*(2*7+2)=2048
根本原因: `fig*_caption.md` 是**手工维护**的文件, 与生成脚本脱节。
没有任何门禁能可靠校验"手写数字 vs 产物", 因为错误值也可能在别处偶然出现。

【解法】
图注由**生成该图的脚本**写出, 其中的统计量从产物**实时计算**。
这样"图注与数据不一致"在生成阶段就不可能发生。

【用法】
在 make_figN.py 末尾:
    from caption_util import write_caption
    write_caption(3, title=..., data=..., n=..., limits=...)

写出的文件固定为 ../fig{N}_caption.md, 带可追溯的生成标记。
"""
from __future__ import annotations

import datetime as _dt
from pathlib import Path

HERE = Path(__file__).resolve().parent


def write_caption(n: int, *, title: str, sections: dict[str, str]) -> Path:
    """写出 figN_caption.md。

    参数
    ----
    n : 图号
    title : 图注标题句
    sections : 有序小标题 -> 正文（如 {"Data": "...", "n": "...", "Limits": "..."}）
    """
    lines = [f"# Figure {n}. {title}", ""]
    for head, body in sections.items():
        lines.append(f"**{head}.** {body.strip()}")
        lines.append("")
    lines.append("---")
    lines.append(
        f"*Auto-generated by `make_fig{n}.py` on "
        f"{_dt.date.today().isoformat()}. Do not edit by hand — regenerate instead.*")
    lines.append("")
    out = HERE / f"fig{n}_caption.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def verify(n: int, required: dict[str, str]) -> list[str]:
    """校验图注是否包含期望的子串（供门禁调用）。"""
    p = HERE / f"fig{n}_caption.md"
    if not p.exists():
        return [f"fig{n}_caption.md 不存在"]
    t = p.read_text(encoding="utf-8")
    return [f"fig{n} 图注缺 {k!r}" for k, v in required.items() if v not in t]
